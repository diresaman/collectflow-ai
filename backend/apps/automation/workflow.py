"""
Interactive workflow view of an AUTOMATION run.

The automated phases (sync, evaluation, generation, finalizing) are persisted as WorkflowStep
rows by the orchestrator. The human phases are *derived* on every read from persisted
follow-ups and delivery attempts, so approvals, rejections, edits and sends keep using the
existing endpoints and services, and a browser refresh simply re-reads the database:

  WAITING_FOR_APPROVAL           drafts from this run still in DRAFT
  WAITING_FOR_SEND_CONFIRMATION  approved reminders not yet sent and not left unsent
  SENDING                        delivery outcomes of this run's reminders

No request or transaction is held open while waiting for the operator.
"""

import datetime as dt
from collections import defaultdict
from dataclasses import dataclass
from typing import Any

from django.db.models import Max, Min
from django.utils import timezone

from apps.followups.models import FollowUp
from apps.followups.serializers import FollowUpSerializer
from apps.followups.services import FollowUpError
from apps.invoices.models import AutomationRun
from apps.invoices.serializers import AutomationRunSerializer

from .lease import fail_abandoned_runs
from .models import AutomationRunItem, WorkflowStep

STEP_ORDER = [
    "SYNCING_INVOICES",
    "EVALUATING_INVOICES",
    "GENERATING_DRAFTS",
    "WAITING_FOR_APPROVAL",
    "WAITING_FOR_SEND_CONFIRMATION",
    "SENDING",
    "FINALIZING",
]
STEP_LABELS = {
    "SYNCING_INVOICES": "Sync invoices from Google Sheets",
    "EVALUATING_INVOICES": "Evaluate invoices",
    "GENERATING_DRAFTS": "Generate drafts with Gemini",
    "WAITING_FOR_APPROVAL": "Review and approve drafts",
    "WAITING_FOR_SEND_CONFIRMATION": "Confirm Gmail sends",
    "SENDING": "Gmail delivery",
    "FINALIZING": "Finalize",
}

DELIVERY_STATUSES = (
    FollowUp.Status.SENDING,
    FollowUp.Status.SENT,
    FollowUp.Status.FAILED,
    FollowUp.Status.DELIVERY_UNKNOWN,
)
EVER_APPROVED = (FollowUp.Status.APPROVED, *DELIVERY_STATUSES)


class WorkflowConflict(FollowUpError):
    code = "workflow_conflict"


@dataclass
class Tracked:
    """A draft generated by this run, followed through regenerations to its current follow-up."""

    item: AutomationRunItem
    follow_up: FollowUp

    @property
    def status(self) -> str:
        return self.follow_up.status


def tracked_follow_ups(run: AutomationRun) -> list[Tracked]:
    items = list(
        run.items.filter(outcome=AutomationRunItem.Outcome.GENERATED, follow_up__isnull=False).select_related("follow_up")
    )
    if not items:
        return []
    invoice_ids = {item.follow_up.invoice_id for item in items}  # type: ignore[union-attr]
    later = FollowUp.objects.filter(invoice_id__in=invoice_ids).select_related("invoice").order_by("-generated_at")
    if run.finalized_at:
        # After finalizing, stop following newer reminders created outside this workflow.
        later = later.filter(generated_at__lte=run.finalized_at)
    by_invoice: dict[Any, list[FollowUp]] = defaultdict(list)
    for follow_up in later:
        by_invoice[follow_up.invoice_id].append(follow_up)

    tracked = []
    for item in items:
        original = item.follow_up
        assert original is not None
        # Regenerating replaces a draft with a newer follow-up for the same invoice.
        current = next(
            (f for f in by_invoice[original.invoice_id] if f.generated_at >= original.generated_at), original
        )
        tracked.append(Tracked(item=item, follow_up=current))
    return tracked


def _step(key: str, status: str, started: dt.datetime | None, completed: dt.datetime | None, detail: str) -> dict[str, Any]:
    return {
        "key": key,
        "label": STEP_LABELS[key],
        "status": status,
        "started_at": started,
        "completed_at": completed,
        "detail": detail,
    }


def build(run: AutomationRun) -> dict[str, Any]:
    stored = {step.key: step for step in run.workflow_steps.all()}
    tracked = tracked_follow_ups(run)
    processing = run.status == AutomationRun.Status.RUNNING
    finalized = run.finalized_at is not None

    drafts = [t for t in tracked if t.status == FollowUp.Status.DRAFT]
    awaiting_send = [
        t for t in tracked if t.status == FollowUp.Status.APPROVED and not t.item.left_unsent_at and not finalized
    ]
    left_unsent = [t for t in tracked if t.status == FollowUp.Status.APPROVED and (t.item.left_unsent_at or finalized)]
    delivered = [t for t in tracked if t.status in DELIVERY_STATUSES]
    count = lambda status: sum(1 for t in tracked if t.status == status)  # noqa: E731

    generation_step = stored.get("GENERATING_DRAFTS")
    review_started = generation_step.completed_at if generation_step else None
    decided_at = max((t.follow_up.updated_at for t in tracked if t.status != FollowUp.Status.DRAFT), default=None)

    # Derived human steps --------------------------------------------------------
    if processing:
        approval = _step("WAITING_FOR_APPROVAL", "PENDING", None, None, "")
    elif not tracked:
        approval = _step("WAITING_FOR_APPROVAL", "SKIPPED", None, None, "No drafts to review.")
    elif drafts and not finalized:
        approval = _step("WAITING_FOR_APPROVAL", "RUNNING", review_started, None, f"{len(drafts)} draft(s) awaiting review.")
    else:
        detail = f"{count(FollowUp.Status.REJECTED)} rejected, {sum(1 for t in tracked if t.status in EVER_APPROVED)} approved."
        if drafts:
            detail += f" {len(drafts)} left for later review."
        approval = _step("WAITING_FOR_APPROVAL", "COMPLETED", review_started, decided_at, detail)

    ever_approved = [t for t in tracked if t.status in EVER_APPROVED]
    if processing or (drafts and not ever_approved and not finalized):
        confirmation = _step("WAITING_FOR_SEND_CONFIRMATION", "PENDING", None, None, "")
    elif not ever_approved:
        confirmation = _step("WAITING_FOR_SEND_CONFIRMATION", "SKIPPED", None, None, "Nothing approved.")
    elif awaiting_send:
        first_approval = min(t.follow_up.approved_at or t.follow_up.updated_at for t in ever_approved)
        confirmation = _step(
            "WAITING_FOR_SEND_CONFIRMATION", "RUNNING", first_approval, None,
            f"{len(awaiting_send)} approved reminder(s) awaiting your confirmation.",
        )
    else:
        first_approval = min(t.follow_up.approved_at or t.follow_up.updated_at for t in ever_approved)
        confirmed = len(delivered)
        confirmation = _step(
            "WAITING_FOR_SEND_CONFIRMATION", "COMPLETED", first_approval, decided_at,
            f"{confirmed} confirmed for sending, {len(left_unsent)} left unsent.",
        )

    sending_now = count(FollowUp.Status.SENDING)
    unknown = count(FollowUp.Status.DELIVERY_UNKNOWN)
    failed = count(FollowUp.Status.FAILED)
    sent = count(FollowUp.Status.SENT)
    last_attempt = (
        FollowUp.objects.filter(pk__in=[t.follow_up.pk for t in delivered])
        .aggregate(last=Max("delivery_attempts__completed_at"), first=Min("delivery_attempts__started_at"))
        if delivered
        else {"last": None, "first": None}
    )
    if not delivered:
        if processing or awaiting_send or (drafts and not finalized):
            sending = _step("SENDING", "PENDING", None, None, "")
        else:
            sending = _step("SENDING", "SKIPPED", None, None, "Nothing was sent.")
    else:
        detail = f"{sent} accepted by Gmail, {failed} failed, {unknown} unknown."
        if sending_now:
            status = "RUNNING"
            detail = f"{sending_now} sending. " + detail
        elif failed or unknown:
            status = "FAILED"
            if unknown:
                detail += " Unknown outcomes need manual reconciliation."
        elif awaiting_send:
            status = "RUNNING"
        else:
            status = "COMPLETED"
        sending = _step("SENDING", status, last_attempt["first"], None if status == "RUNNING" else last_attempt["last"], detail)

    def stored_step(key: str) -> dict[str, Any]:
        step = stored.get(key)
        if step is None:  # runs created before workflow tracking existed
            return _step(key, "COMPLETED" if not processing else "PENDING", None, None, "")
        return _step(key, step.status, step.started_at, step.completed_at, step.detail)

    steps = [
        stored_step("SYNCING_INVOICES"),
        stored_step("EVALUATING_INVOICES"),
        stored_step("GENERATING_DRAFTS"),
        approval,
        confirmation,
        sending,
        stored_step("FINALIZING"),
    ]

    if processing:
        state = "PROCESSING"
    elif finalized:
        state = "FINALIZED"
    elif sending_now:
        state = "SENDING"
    elif drafts:
        state = "WAITING_FOR_APPROVAL"
    elif awaiting_send:
        state = "WAITING_FOR_SEND_CONFIRMATION"
    else:
        state = "READY_TO_FINALIZE"
    current_step = next((s["key"] for s in steps if s["status"] in ("RUNNING", "PENDING")), "FINALIZING")
    if finalized:
        current_step = "FINALIZING"

    def entry(t: Tracked) -> dict[str, Any]:
        return {"item_id": t.item.pk, "follow_up": FollowUpSerializer(t.follow_up).data}

    attention = [
        {
            "item_id": item.pk,
            "invoice_id": str(item.invoice_id) if item.invoice_id else None,
            "invoice_external_id": item.invoice_external_id,
            "reason_code": item.reason_code,
            "detail": item.detail,
        }
        for item in run.items.filter(reason_code__in=["stale_draft", "stale_approved", "delivery_unresolved"])
    ]

    return {
        "id": run.pk,
        "state": state,
        "current_step": current_step,
        "run": AutomationRunSerializer(run).data,
        "steps": steps,
        "summary": {
            "invoices_evaluated": run.invoices_evaluated,
            "invoices_overdue": run.invoices_overdue,
            "drafts_generated": run.drafts_generated,
            "generation_failures": run.generation_failures,
            "drafts_pending_review": len(drafts),
            "drafts_approved": len(ever_approved),
            "drafts_rejected": count(FollowUp.Status.REJECTED),
            "awaiting_send_confirmation": len(awaiting_send),
            "approved_left_unsent": len(left_unsent),
            "sending": sending_now,
            # Gmail accepted the message for delivery; this is not proof the recipient received it.
            "gmail_submissions_confirmed": sent,
            "delivery_failed": failed,
            "delivery_unknown": unknown,
        },
        "pending_actions": {
            "approvals": [entry(t) for t in drafts] if not finalized else [],
            "send_confirmations": [entry(t) for t in awaiting_send],
            "deliveries": [entry(t) for t in delivered],
            "left_unsent": [entry(t) for t in left_unsent],
            "attention": attention,
        },
        "can_finalize": not processing and not finalized and not sending_now,
    }


def current_run() -> AutomationRun | None:
    """The workflow to show: a processing run, else the latest open one, else the latest."""
    fail_abandoned_runs()
    runs = AutomationRun.objects.filter(kind=AutomationRun.Kind.AUTOMATION)
    return (
        runs.filter(status=AutomationRun.Status.RUNNING).first()
        or runs.filter(finalized_at__isnull=True).first()
        or runs.first()
    )


def finalize(run: AutomationRun) -> AutomationRun:
    """Closes the workflow. Approved reminders not yet sent are left unsent (still APPROVED)."""
    if run.finalized_at:
        return run  # idempotent
    if run.status == AutomationRun.Status.RUNNING:
        raise WorkflowConflict("The run is still processing; wait for it to finish.")
    tracked = tracked_follow_ups(run)
    if any(t.status == FollowUp.Status.SENDING for t in tracked):
        raise WorkflowConflict("A Gmail delivery is in progress; wait for it to finish.")

    now = timezone.now()
    if AutomationRun.objects.filter(pk=run.pk, finalized_at__isnull=True).update(finalized_at=now) != 1:
        run.refresh_from_db()
        return run
    left = [t.item.pk for t in tracked if t.status == FollowUp.Status.APPROVED and not t.item.left_unsent_at]
    AutomationRunItem.objects.filter(pk__in=left).update(left_unsent_at=now)
    pending = sum(1 for t in tracked if t.status == FollowUp.Status.DRAFT)
    detail = f"Finalized. {len(left)} approved reminder(s) left unsent."
    if pending:
        detail += f" {pending} draft(s) stay in the dashboard approval queue."
    WorkflowStep.objects.filter(run=run, key=WorkflowStep.Key.FINALIZING).update(
        status=WorkflowStep.Status.COMPLETED, started_at=now, completed_at=now, detail=detail[:300]
    )
    run.refresh_from_db()
    return run


def leave_unsent(run: AutomationRun, item_id: int) -> AutomationRun:
    """Removes an approved reminder from this workflow's send queue. It stays APPROVED and can be sent later."""
    if run.finalized_at:
        raise WorkflowConflict("This workflow is already finalized.")
    tracked = {t.item.pk: t for t in tracked_follow_ups(run)}
    entry = tracked.get(item_id)
    if entry is None:
        raise AutomationRunItem.DoesNotExist
    if entry.status != FollowUp.Status.APPROVED:
        raise WorkflowConflict(f"Only approved, unsent reminders can be left unsent (this one is {entry.status}).")
    AutomationRunItem.objects.filter(pk=item_id, left_unsent_at__isnull=True).update(left_unsent_at=timezone.now())
    return run
